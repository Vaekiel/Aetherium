import assert from 'node:assert/strict';
import {CARDS} from '../src/collection-data.js';
import {journeyProgress} from '../src/journey-progress.js';
import {FINISH_KEYS,restoreFinishCounts} from '../src/finishes.js';
import {recordPersonalBest,TRIAL_RECORD_MODES} from '../src/trial-records.js';
import {COLLECTION_MILESTONES} from '../src/collection-milestones.js';
import {EXPEDITION_ROUTES} from '../src/expeditions.js';
const flat=state=>journeyProgress(CARDS,state).flatMap(g=>g.tracks);
const find=(state,id)=>flat(state).find(t=>t.id===id);
const fresh={owned:{},finishCounts:{},wins:0,trialStats:[],trialRecords:[],collectionMilestones:{},alchemyKnown:[]};
assert.equal(flat(fresh).length,8);
assert.ok(flat(fresh).every(t=>t.current===0&&t.achieved===0&&!t.complete));
assert.equal(find(fresh,'marches-de-verre-finishes').total,285);
assert.equal(find(fresh,'marches-de-verre-cards').total,72);
assert.ok(flat(fresh).every(t=>!t.id.includes('plateau')));
const legacy={...fresh,wins:50,trialStats:[{wins:50,bestMode:'maitrise',bestScore:100}],owned:{1:2,72:1},shiny:{1:true}};
legacy.finishCounts=restoreFinishCounts(legacy.owned,legacy.shiny);
assert.equal(find(legacy,'wins').achieved,2);assert.equal(find(legacy,'wins').next,100);
assert.equal(find(legacy,'versatility').current,0,'Legacy aggregates do not invent mode records');
assert.equal(find(legacy,'medals').current,1);
assert.equal(find(legacy,'marches-de-verre-finishes').current,2,'Normal Signature excluded from permanent finish objective');
const state={...fresh,owned:Object.fromEntries(CARDS.map(c=>[c.id,c.signature?1:4])),shiny:Object.fromEntries(CARDS.map(c=>[c.id,true])),finishCounts:Object.fromEntries(FINISH_KEYS.map(f=>[f,Object.fromEntries(CARDS.filter(c=>!c.signature||f==='chromatic').map(c=>[c.id,1]))])),wins:999,alchemyKnown:Array.from({length:20},(_,i)=>i),expedition:{completedRoutes:EXPEDITION_ROUTES.map(r=>r.id)},collectionMilestones:Object.fromEntries(Object.entries(COLLECTION_MILESTONES).map(([k,v])=>[k,v.map(m=>m.threshold)]))};
let records=[];for(let i=0;i<5;i++)for(const mode of TRIAL_RECORD_MODES)records=recordPersonalBest(records,i,mode,100,{errors:0,moves:8,attempts:0,hints:0});
state.trialRecords=records;
const before=JSON.stringify(state),complete=flat(state);
assert.ok(complete.every(t=>t.complete&&t.percent===100&&t.next===null));
assert.equal(complete.reduce((n,t)=>n+t.achieved,0),27);
assert.equal(find(state,'wins').current,999);
assert.equal(find(state,'medals').current,15);
assert.equal(find(state,'versatility').current,15);
assert.equal(JSON.stringify(state),before);
const bad={...fresh,alchemyKnown:[0,0,1,-1,20],expedition:{completedRoutes:['verriers','verriers','unknown']},trialRecords:[{maitrise:{wins:3,bestScore:200,lastScore:100,bestMetric:0}}]};
assert.equal(find(bad,'alchemy').current,2);assert.equal(find(bad,'routes').current,1);assert.equal(find(bad,'versatility').current,0);
console.log('Journey progression: 8 tracks, 27 permanent milestones, legacy and full saves, Signature exclusion, no future content and no state mutation OK.');
