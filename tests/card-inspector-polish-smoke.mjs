import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
const js=read('../src/main.js'),css=read('../src/card-inspector-polish.css'),codex=read('../src/codex.css'),html=read('../index.html');
assert.match(js,/panel\.classList\.add\('is-card-polished'\)/);
assert.match(js,/panel\.classList\.remove\('is-card-polished','recto-lab-mode-new'\)/);
assert.doesNotMatch(js,/if\(c\.id===8\)/,'Every revealed card uses the same panel, not only Cerf');
assert.match(js,/applyCardIllustration\(img,c,\{shiny:chromatic,size:'full'\}\)/);
assert.match(js,/panel\.append\(artwork,copy\)/);
assert.doesNotMatch(js,/makePilotCardFront|pilot-card-front/);
assert.match(css,/\.inspector\.is-card-polished/);
assert.doesNotMatch(css,/is-card-polish-cerf/);
assert.match(css,/\.inspector-copy > h2/);
assert.match(css,/\.inspector-copy > \.stats/);
assert.match(css,/\.inspector-copy > \.stats > span/);
assert.doesNotMatch(css,/inspector-art-shell|\.inspector img|url\(/);
assert.match(codex,/@import url\('\.\/card-inspector-polish\.css\?v=codex-stats-hd-all-1'\)/);
assert.match(html,/inspector=codex-stats-hd-all-1/);
assert.match(html,/polish=codex-stats-hd-all-1/);
assert.match(js,/visualStats=\[/);
assert.match(js,/c\.attack\+c\.health/);
assert.match(js,/stat-inventory-total/);
assert.match(css,/stat-name/);
assert.match(css,/stat-glyph/);
assert.match(css,/stat-value/);
assert.match(css,/:not\(\.stat-inventory-total\)/);
assert.equal(existsSync(new URL('../assets/cards/cerf-des-lueurs.webp',import.meta.url)),true);
for(const kind of ['eclat','garde','flux']){
  const path='../assets/icons/stat-'+kind+'-hd.webp';
  const webp=readFileSync(new URL(path,import.meta.url));
  assert.equal(webp.toString('ascii',0,4),'RIFF','Valid RIFF WebP: '+kind);
  assert.equal(webp.toString('ascii',8,12),'WEBP','Actual WebP data: '+kind);
  assert.ok(webp.length>1000&&webp.length<45000,'HD icon optimized for browser: '+kind);
  assert.ok(js.includes('./assets/icons/stat-'+kind+'-hd.webp'),'Approved icon in Codex: '+kind);
}
assert.match(css,/width:48px!important;height:48px!important/);
assert.match(css,/image-rendering:pixelated!important/);
assert.doesNotMatch(js,/stat-(eclat|garde|flux)\.svg/);
console.log('Aetherium Codex: all revealed cards use 3 HD pixel-art glyphs; sealed and original artworks preserved');
