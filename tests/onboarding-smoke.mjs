import assert from 'node:assert/strict';
import {beginnerGuide,readGuideDismissal,writeGuideDismissal,GUIDE_PREF_KEY} from '../src/onboarding.js';
import {PACK_PRICE} from '../src/data.js';
const fresh={coins:300,opened:0,wins:0,owned:{}};
assert.deepEqual(beginnerGuide(fresh,PACK_PRICE),{collected:false,won:false,complete:false,canBuy:true,stage:'pack'});
assert.equal(beginnerGuide({...fresh,coins:99},PACK_PRICE).stage,'trial');
assert.equal(beginnerGuide({...fresh,opened:1,owned:{1:1}},PACK_PRICE).stage,'trial');
assert.equal(beginnerGuide({...fresh,opened:1,wins:1,owned:{1:1}},PACK_PRICE).complete,true);
assert.equal(beginnerGuide({...fresh,owned:{25:1},wins:1},PACK_PRICE).complete,true);
assert.equal(beginnerGuide({...fresh,wins:1},PACK_PRICE).stage,'pack');
const before=JSON.stringify(fresh);beginnerGuide(fresh,PACK_PRICE);assert.equal(JSON.stringify(fresh),before);
const values=new Map([['aetherium-save-v1','original']]);
const storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};
assert.equal(readGuideDismissal(storage),false);
writeGuideDismissal(storage,true);assert.equal(values.get(GUIDE_PREF_KEY),'1');assert.equal(readGuideDismissal(storage),true);
writeGuideDismissal(storage,false);assert.equal(readGuideDismissal(storage),false);assert.equal(values.get('aetherium-save-v1'),'original');
assert.equal(readGuideDismissal({getItem(){throw Error('blocked')}}),false);
assert.doesNotThrow(()=>writeGuideDismissal({setItem(){throw Error('quota')}},true));
console.log('Onboarding: real progress, affordable pack, completion, independent dismissal and blocked storage OK.');
